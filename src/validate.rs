//! Data integrity checks for `data/wiki.json`, the split files in
//! `data/wiki/`, `data/media.json` and the media folders. Report only:
//! nothing here rewrites data. `--import` runs the same wiki checks on a
//! batch before anything is written.
//!
//! Run with `gta6-hq --validate` (exit code 1 if there are errors) or read
//! the same report from `/api/health`.

use std::{collections::BTreeSet, fmt::Write as _, path::Path};

use serde::Serialize;
use serde_json::Value;

use crate::{
    content::{self, CONFIDENCE_LEVELS, FIELD_TYPES, STATUSES},
    media,
};

