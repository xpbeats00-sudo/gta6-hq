"""List every media file the validator flags as `rights-unconfirmed`, with a cautious next step for each.

    python scripts/rights_report.py                  # rule reproduced from data/media.json, cross-checked against the validator if built
    python scripts/rights_report.py --no-validator   # skip running target/release/gta6-hq.exe --validate
    python scripts/rights_report.py --validator-output report.md   # cross-check against a saved validator report instead

Writes docs/compliance/RIGHTS-WARNINGS-REPORT.md and docs/compliance/rights-warnings.csv.
Read-only: no image and no record in data/media.json is changed, and nothing is fetched from the web.
Standard library only. Exit code 1 if the reproduced list and the validator's list differ.

The rule is the one in src/validate.rs: a record whose `rights_status` is one of the four known states,
is not `approved`, and whose `approval_status` is `approved` (shown in the app) gets one warning.
The recommended actions below are derived only from what each record states (source URL, creator,
licence text, derived_from). Nothing here is legal advice, and no record is treated as licensed.
"""
import collections, csv, datetime, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'docs', 'compliance')
EXE = os.path.join(ROOT, 'target', 'release', 'gta6-hq.exe' if os.name == 'nt' else 'gta6-hq')
NOW = datetime.datetime.now().strftime('%Y-%m-%d %H:%M')

RIGHTS_STATES = ('approved', 'permission_required', 'unknown', 'rejected')  # media::RIGHTS_STATES
OFFICIAL_DOMAINS = {'rockstargames.com'}

# Recommended actions. Keys are stable; the text is what goes in the report.
ACTIONS = {
    'official': 'Official Rockstar press/marketing asset — keep, request or confirm press-kit terms',
    'official_frame': 'Frame cut from an official Rockstar video — keep only if press-kit terms cover stills; confirm, or swap for an official screenshot',
    'owner_official': 'Owner-supplied copy of official Rockstar art (no URL) — find it on Rockstar\'s official media page to confirm origin, then confirm press-kit terms',
    'official_via_third_party': 'Rockstar imagery taken from a third-party site — re-source the same picture from Rockstar\'s official pages (then confirm press-kit terms), or ask the site',
    'trophy': 'Platform trophy artwork copied from a third-party trophy list — confirm terms with Rockstar/Sony, or replace with a self-captured icon',
    'third_party': 'Third-party site screenshot — ask the site for permission or replace with an official/self-captured shot',
    'third_party_photo': 'Third-party photograph (news agency or other rights holder, not game imagery) — licence it from the named holder or remove from the release build',
    'trademark': 'Trademark/logo use (Take-Two) — confirm fan-content/trademark terms; keep use nominative or remove from the release build',
    'derived': 'Project-made derivative — rights follow the parent asset; record the derivation and resolve the parent\'s rights first',
    'self_captured': 'Self-captured / generated by project — record that fact if verified',
    'no_source': 'No source recorded — find source or remove from the release build',
}
ACTION_ORDER = list(ACTIONS)

URL_RE = re.compile(r'https?://[^\s,;)"\]]+')
AGENCY_RE = re.compile(r'getty|reuters|nurphoto|associated press|\bap photo|afp|\(image via (?!rockstar)', re.I)
ROCKSTAR_CREDIT_RE = re.compile(r'(credited to|supplied by) rockstar', re.I)
NO_LICENCE_RE = re.compile(r'no (formal )?licen[cs]e recorded', re.I)


def load(rel):
    with open(os.path.join(ROOT, rel), encoding='utf-8-sig') as f:
        return json.load(f)


def domain(url):
    host = url.split('/')[2].lower()
    return host[4:] if host.startswith('www.') else host


def flagged(assets):
    """Reproduces src/validate.rs: one `rights-unconfirmed` warning per matching record."""
    return [a for a in assets
            if a.get('rights_status', '') in RIGHTS_STATES
            and a.get('rights_status') != 'approved'
            and a.get('approval_status', '') == 'approved']


def validator_subjects(path=None):
    """The subjects of `rights-unconfirmed` rows in a validator report (saved, or produced by running the exe)."""
    if path:
        with open(path, encoding='utf-8', errors='replace') as f:
            text = f.read()
    elif os.path.exists(EXE):
        text = subprocess.run([EXE, '--validate'], cwd=ROOT, capture_output=True, text=True, encoding='utf-8', errors='replace').stdout
    else:
        return None, None
    rows = re.findall(r'^\| `rights-unconfirmed` \| `([^`]+)` \|', text, re.M)
    total = re.search(r'\*\*(\d+) errors?, (\d+) warnings?\*\*', text)
    return rows, (int(total.group(2)) if total else None)


def is_derived(a):
    src = a.get('source', '')
    return bool(a.get('derived_from')) or src.startswith(('Made by this project', 'Still from wallpapers/', 'Frame of wallpapers/', 'Crop of images/'))


def is_derived_text(a):
    return a.get('source', '').startswith(('Made by this project', 'Still from wallpapers/', 'Frame of wallpapers/', 'Crop of images/', 'Cut by this project', 'Cropped by this project'))


def classify(a, records, depth=0):
    """Returns an ACTIONS key from the record's own fields, or None if no rule fits."""
    creator = a.get('creator', '').strip()
    src = a.get('source', '').strip()
    lic = a.get('license', '').strip()
    low_src, low_creator = src.lower(), creator.lower()
    urls = URL_RE.findall(src)
    domains = {domain(u) for u in urls}

    if re.search(r'self-captured|captured by this project|screenshot taken by this project|generated by this project', low_src):
        return 'self_captured'
    if is_derived(a):
        return 'derived'
    if 'trademark' in low_creator or 'trademark' in lic.lower():
        return 'trademark'
    if creator in ('', 'Unknown') and not urls:
        return 'no_source'
    if AGENCY_RE.search(creator):
        return 'third_party_photo'
    if domains & OFFICIAL_DOMAINS or any('x.com/rockstargames/' in u.lower() for u in urls):
        if low_src.startswith('frame at') or 'frame of the official video' in lic.lower():
            return 'official_frame'
        return 'official'
    if 'exophase.com' in domains or 'trophy' in low_src:
        return 'trophy'
    if urls and (low_creator.startswith('rockstar games') or ROCKSTAR_CREDIT_RE.search(creator)
                 or low_src.startswith(("rockstar picture published at", "crop of rockstar's"))
                 or any('officialscreenshots' in u.lower() for u in urls)):
        return 'official_via_third_party'
    if not urls and low_creator.startswith('rockstar games') and 'supplied by the app owner' in low_src:
        return 'owner_official'
    if urls:
        return 'third_party'
    return None


def parent_of(a, records):
    p = a.get('derived_from') or ''
    if not p:
        m = re.search(r'((?:wallpapers|images)/[^\s,;]+\.\w+)', a.get('source', ''))
        p = m.group(1) if m else ''
    return p


def source_group(a, urls):
    if urls:
        return domain(urls[0])
    src = a.get('source', '').lower()
    if is_derived(a):
        return '(no URL) made by this project from another file'
    if 'supplied by the app owner' in src:
        return '(no URL) supplied by the app owner'
    if 'discord' in src:
        return '(no URL) downloaded from Discord'
    return '(no URL) ' + (a.get('source', '')[:40] or 'nothing recorded')


def licence_text(a):
    lic = a.get('license', '').strip()
    if lic in ('', 'Unknown'):
        return 'none recorded'
    return f'none recorded (record states: "{lic}")'


def unconfirmed(a, key, parent, parent_rec):
    gaps = [f'rights_status is `{a.get("rights_status")}`; no licence or written permission recorded']
    lic = a.get('license', '')
    if key in ('official', 'official_frame'):
        if 'offered on the official media page to download and share' in lic.lower():
            gaps.append('the official media page\'s download-and-share terms are not recorded or confirmed to cover an app')
        else:
            gaps.append('not recorded as offered for download on the official media page; press-kit terms unconfirmed')
    elif key == 'owner_official':
        gaps.append('no URL showing where the owner got it; origin on Rockstar\'s pages unverified')
    elif key == 'official_via_third_party':
        gaps.append('copy taken from a third-party site, not Rockstar; whether the site altered or cropped it and on what terms it was published')
    elif key == 'trophy':
        gaps.append('icon copied from a third-party trophy list; terms from Rockstar/Sony unconfirmed')
    elif key == 'third_party':
        gaps.append('permission from the publishing site; who captured the picture')
    elif key == 'third_party_photo':
        gaps.append('the photographer/agency licence; it is not game imagery')
    elif key == 'trademark':
        gaps.append('trademark-use terms from Take-Two/Rockstar')
    elif key == 'derived':
        if not parent:
            gaps.append('the parent file is not named')
        elif parent_rec is None:
            gaps.append(f'the parent `{parent}` has no record in data/media.json')
        else:
            gaps.append(f'the parent `{parent}` is itself `{parent_rec.get("rights_status")}`')
    elif key == 'no_source':
        gaps.append('original source and creator')
    if a.get('creator', '').strip() in ('', 'Unknown'):
        gaps.append('creator unknown')
    if not a.get('accessed'):
        gaps.append('no retrieval date')
    return '; '.join(gaps)


def md(s):
    return str(s).replace('|', '\\|').replace('\n', ' ')


def main(argv):
    media = load('data/media.json')
    assets = media['assets']
    records = {a['file']: a for a in assets}
    rows = []
    unclassified = []
    conflicts = []
    for a in flagged(assets):
        urls = URL_RE.findall(a.get('source', ''))
        key = classify(a, records)
        parent = parent_of(a, records) if key == 'derived' else ''
        parent_rec = records.get(parent) if parent else None
        action = ACTIONS.get(key, 'UNCLASSIFIED — review this record by hand')
        if key == 'derived':
            root, seen = parent_rec, {a['file']}
            while root is not None and is_derived(root) and root['file'] not in seen:
                seen.add(root['file'])
                root = records.get(parent_of(root, records))
            pkey = classify(root, records) if root else None
            if pkey and pkey != 'derived':
                action += f' (parent: {ACTIONS[pkey].split(" — ")[0]})'
            elif parent and parent_rec is None:
                action += ' (parent not recorded)'
        if key is None:
            unclassified.append(a['file'])
        if a.get('derived_from') and URL_RE.search(a.get('source', '')) and not is_derived_text(a):
            conflicts.append((a['file'], a['derived_from'], ' '.join(urls)))
        rows.append({
            'Asset': a['file'],
            'Folder': os.path.dirname(a['file']),
            'Rights status': a.get('rights_status', ''),
            'Source group': source_group(a, urls),
            'Source': ' '.join(urls) if urls else (a.get('source', '') or 'nothing recorded'),
            'Existing attribution/credit': a.get('creator', '') or 'none recorded',
            'Known licence': licence_text(a),
            'Unconfirmed': unconfirmed(a, key, parent, parent_rec),
            'Action key': key or 'unclassified',
            'Recommended action': action,
        })

    # Cross-check against the validator.
    args = argv[1:]
    check_note, mismatch = 'Validator not run (`--no-validator`).', False
    if '--no-validator' not in args:
        path = args[args.index('--validator-output') + 1] if '--validator-output' in args else None
        subjects, total = validator_subjects(path)
        if subjects is None:
            check_note = f'Validator not found at `{os.path.relpath(EXE, ROOT)}`; rule reproduced from `data/media.json` only.'
        else:
            mine = collections.Counter(r['Asset'] for r in rows)
            theirs = collections.Counter(subjects)
            mismatch = mine != theirs
            check_note = (f'`gta6-hq --validate` reports {total} warnings in all, {len(subjects)} of them `rights-unconfirmed`; '
                          f'this report has {len(rows)} rows. ' + ('**The lists differ.**' if mismatch else 'The two lists match file for file.'))
            if mismatch:
                check_note += f' Only here: {sorted(mine - theirs)}. Only in validator: {sorted(theirs - mine)}.'
            if total is not None and total != len(subjects):
                check_note += f' The other {total - len(subjects)} warning(s) are other checks and are not part of this report.'

    os.makedirs(OUT, exist_ok=True)
    cols = ['Asset', 'Folder', 'Rights status', 'Source group', 'Source', 'Existing attribution/credit', 'Known licence', 'Unconfirmed', 'Action key', 'Recommended action']
    with open(os.path.join(OUT, 'rights-warnings.csv'), 'w', encoding='utf-8', newline='') as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        for r in sorted(rows, key=lambda r: (r['Source group'], r['Asset'])):
            w.writerow(r)

    def table(counter, head, order=None):
        out = [f'| {head} | Files |', '|---|---|']
        items = [(k, counter[k]) for k in order if counter.get(k)] if order else counter.most_common()
        return out + [f'| {md(k)} | {v} |' for k, v in items] + [f'| **Total** | **{sum(counter.values())}** |']

    by_status = collections.Counter(r['Rights status'] for r in rows)
    by_group = collections.Counter(r['Source group'] for r in rows)
    by_creator = collections.Counter(r['Existing attribution/credit'] for r in rows)
    by_folder = collections.Counter(r['Folder'] for r in rows)
    by_action = collections.Counter(r['Action key'] for r in rows)

    lines = ['# Rights warnings report', '',
             f'Generated {NOW} by `scripts/rights_report.py` from `data/media.json`. Do not edit by hand. Read-only: no file or record was changed and nothing was fetched from the web.', '',
             'Every row is a media file that `gta6-hq --validate` flags as `rights-unconfirmed`: it is shown in the app (`approval_status: approved`) but its `rights_status` is not `approved`. '
             'Recommended actions come only from what each record states. **No file here has a recorded licence**, and nothing here is legal advice.', '',
             '## Check against the validator', '', check_note, '',
             '## Summary', '', f'**{len(rows)} files.**', '',
             '### By rights status', ''] + table(by_status, 'rights_status') + [
             '', '### By recommended action', '',
             '| Action | Files |', '|---|---|']
    lines += [f'| {md(ACTIONS.get(k, "UNCLASSIFIED — review by hand"))} | {by_action[k]} |' for k in ACTION_ORDER + ['unclassified'] if by_action.get(k)]
    lines += [f'| **Total** | **{len(rows)}** |', '',
              '### By source site (domain of the first URL in `source`)', ''] + table(by_group, 'Source') + [
              '', '### By credited creator/publisher', ''] + table(by_creator, 'Creator') + [
              '', '### By image folder', ''] + table(collections.Counter(dict(sorted(by_folder.items()))), 'Folder') + ['']
    if conflicts:
        lines += ['### Records that contradict themselves', '',
                  'These name an outside source URL but also a `derived_from` parent file. They are treated as derivatives (the more cautious reading) until the record is corrected.', '']
        lines += [f'- `{f}`: `derived_from` is `{p}`, but `source` gives {u}' for f, p, u in conflicts] + ['']
    if unclassified:
        lines += ['### Could not classify', ''] + [f'- `{f}`' for f in unclassified] + ['']
    lines += ['## Files by source', '',
              'Grouped by source site; within a group, by recommended action and file name. The same rows are in `rights-warnings.csv`.', '']
    groups = collections.defaultdict(list)
    for r in rows:
        groups[r['Source group']].append(r)
    for g, _ in by_group.most_common():
        items = sorted(groups[g], key=lambda r: (ACTION_ORDER.index(r['Action key']) if r['Action key'] in ACTIONS else 99, r['Asset']))
        lines += [f'### {md(g)} ({len(items)})', '',
                  '| Asset | Source | Existing attribution/credit | Known licence | Unconfirmed | Recommended action |',
                  '|---|---|---|---|---|---|']
        lines += [f'| `{md(r["Asset"])}` | {md(r["Source"])} | {md(r["Existing attribution/credit"])} | {md(r["Known licence"])} | {md(r["Unconfirmed"])} | {md(r["Recommended action"])} |' for r in items]
        lines.append('')
    with open(os.path.join(OUT, 'RIGHTS-WARNINGS-REPORT.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))

    print(f'{len(rows)} rights-unconfirmed files; unclassified {len(unclassified)}; self-contradicting {conflicts}')
    print(check_note)
    print('status:', dict(by_status))
    print('action:', dict(by_action))
    print('top sources:', by_group.most_common(10))
    return 1 if mismatch else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
