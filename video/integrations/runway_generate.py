"""Runway image-to-video or text-to-video, standard library only.

    python video/integrations/runway_generate.py --prompt "slow push over a neon street at dusk" --out clip.mp4
        [--image still.jpg] [--model gen4_turbo] [--ratio 1280:720] [--seconds 5] --yes

Status: written from the official API guide (POST https://api.dev.runwayml.com/v1/image_to_video and
/v1/text_to_video, header X-Runway-Version: 2024-11-06, then poll GET /v1/tasks/{id}) but NOT TESTED,
because no key has been connected and no credits have been bought. Model names and prices change:
check https://docs.dev.runwayml.com/ before the first run.

It refuses to run without RUNWAYML_API_SECRET in video/.env, and without --yes, because every
generation spends paid credits. Rules for anything it makes: register the clip in the production's
assets.json, never present it as footage of the game, never imitate Rockstar's footage or logo.
"""
import argparse
import base64
import json
import mimetypes
import os
import sys
import time
import urllib.error
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import env  # noqa: E402

BASE = 'https://api.dev.runwayml.com/v1'


def call(method, path, key, body=None):
    req = urllib.request.Request(BASE + path, data=json.dumps(body).encode('utf-8') if body else None, method=method,
                                 headers={'Authorization': f'Bearer {key}', 'X-Runway-Version': '2024-11-06', 'Content-Type': 'application/json'})
    try:
        with urllib.request.urlopen(req, timeout=120) as r:
            return json.load(r)
    except urllib.error.HTTPError as e:
        raise SystemExit(f'Runway refused the request: HTTP {e.code} {e.read().decode("utf-8", "replace")[:300]}')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--prompt', required=True); ap.add_argument('--out', required=True); ap.add_argument('--image')
    ap.add_argument('--model', default='gen4_turbo'); ap.add_argument('--ratio', default='1280:720'); ap.add_argument('--seconds', type=int, default=5)
    ap.add_argument('--yes', action='store_true', help='confirm that the owner approved spending credits on this generation')
    a = ap.parse_args()
    key = env.require('RUNWAYML_API_SECRET', 'Runway AI footage', 'https://dev.runway.com/ (create a project, then API Keys)')
    if not a.yes:
        raise SystemExit(f'This would spend Runway credits ({a.seconds}s with {a.model}). Ask the owner, then run again with --yes. Nothing was sent.')
    body = {'model': a.model, 'promptText': a.prompt, 'ratio': a.ratio, 'duration': a.seconds}
    if a.image:
        mime = mimetypes.guess_type(a.image)[0] or 'image/jpeg'
        with open(a.image, 'rb') as f:
            body['promptImage'] = f'data:{mime};base64,' + base64.b64encode(f.read()).decode('ascii')
        task = call('POST', '/image_to_video', key, body)
    else:
        task = call('POST', '/text_to_video', key, body)
    while True:
        time.sleep(6)
        state = call('GET', f"/tasks/{task['id']}", key)
        if state.get('status') == 'SUCCEEDED':
            urllib.request.urlretrieve(state['output'][0], a.out)
            print(f"{a.out}: generated by Runway {a.model}; add it to assets.json (source: Runway, prompt: {a.prompt!r})")
            return 0
        if state.get('status') in ('FAILED', 'CANCELLED'):
            raise SystemExit(f"Runway task {state.get('status')}: {state.get('failure', '')}")


if __name__ == '__main__':
    sys.exit(main())
