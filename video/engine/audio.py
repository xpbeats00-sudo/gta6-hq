"""Audio: original synthesised music, transition effects, narration, and the loudness-normalised mix.

Everything here is generated by this code (no samples, no downloaded audio), so the studio owns it.
Narration engines: 'sapi' (Windows built-in voice, test narration), 'flite' (ffmpeg built-in voice,
test narration), 'elevenlabs' (needs a key, see video/integrations), 'none'.
"""
import json
import os
import re
import subprocess
import wave

import numpy as np

from . import timeline
from .config import QA

SR = 48000


# ---------- wav io ----------
def write_wav(path, data):
    data = np.clip(data, -1, 1)
    if data.ndim == 1:
        data = np.stack([data, data], axis=1)
    with wave.open(path, 'wb') as f:
        f.setnchannels(2)
        f.setsampwidth(2)
        f.setframerate(SR)
        f.writeframes((data * 32767).astype('<i2').tobytes())


def read_audio(path):
    """Decode any audio file to float stereo at 48 kHz through ffmpeg."""
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', path, '-f', 's16le', '-ac', '2', '-ar', str(SR), '-'],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype='<i2').reshape(-1, 2).astype(np.float32) / 32768.0


def db(x):
    return 10 ** (x / 20.0)


def place(track, clip, at, gain=1.0):
    i = int(at * SR)
    if i >= len(track):
        return
    n = min(len(clip), len(track) - i)
    if clip.ndim == 1:
        clip = np.stack([clip, clip], axis=1)
    track[i:i + n] += clip[:n] * gain


# ---------- synthesis ----------
def note(semitones_from_a2):
    return 110.0 * 2 ** (semitones_from_a2 / 12.0)


def saw(freq, n, cutoff=2400.0, detune=0.0):
    t = np.arange(n) / SR
    out = np.zeros(n, dtype=np.float32)
    f = freq * (1 + detune)
    for k in range(1, max(2, int(cutoff / f)) + 1):
        out += np.sin(2 * np.pi * k * f * t) / k * (1 - k * f / (cutoff * 1.4))
    return out * 0.5


def env(n, attack, release):
    e = np.ones(n, dtype=np.float32)
    a, r = min(n, int(attack * SR)), min(n, int(release * SR))
    if a:
        e[:a] = np.linspace(0, 1, a)
    if r:
        e[-r:] *= np.linspace(1, 0, r)
    return e


def noise_band(n, lo, hi, rng):
    spec = np.fft.rfft(rng.standard_normal(n))
    f = np.fft.rfftfreq(n, 1 / SR)
    spec[(f < lo) | (f > hi)] = 0
    out = np.fft.irfft(spec, n).astype(np.float32)
    return out / (np.max(np.abs(out)) + 1e-9)


def kick():
    n = int(0.32 * SR)
    t = np.arange(n) / SR
    f = 45 + 95 * np.exp(-t * 28)
    return (np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 11)).astype(np.float32)


def hat(rng, length=0.05):
    n = int(length * SR)
    return noise_band(n, 7000, 16000, rng) * np.exp(-np.arange(n) / SR * 70)


def clap(rng):
    n = int(0.18 * SR)
    return noise_band(n, 900, 6000, rng) * np.exp(-np.arange(n) / SR * 24)


def whoosh(rng, length=0.8):
    n = int(length * SR)
    x = np.linspace(0, 1, n)
    low, high = noise_band(n, 150, 1200, rng), noise_band(n, 1500, 9000, rng)
    shape = np.sin(np.pi * x) ** 2
    mono = (low * (1 - x) + high * x) * shape
    pan = x
    return np.stack([mono * (1 - pan * 0.6), mono * (0.4 + pan * 0.6)], axis=1).astype(np.float32)


def impact(rng):
    n = int(1.4 * SR)
    t = np.arange(n) / SR
    thump = np.sin(2 * np.pi * np.cumsum(38 + 60 * np.exp(-t * 14)) / SR) * np.exp(-t * 3.2)
    tail = noise_band(n, 200, 3000, rng) * np.exp(-t * 5) * 0.25
    return (thump + tail).astype(np.float32)


def make_music(duration, bpm=104, seed=6):
    """Original synth score in A minor (Am - F - C - G): pad, bass, plucked arpeggio and light drums.
    Arrangement follows the video: quiet opening, build, full middle, pad-only ending."""
    rng = np.random.default_rng(seed)
    n = int(duration * SR) + SR
    track = np.zeros((n, 2), dtype=np.float32)
    beat = 60.0 / bpm
    bar = beat * 4
    chords = [(0, 3, 7), (-4, 0, 3), (3, 7, 10), (-2, 2, 5)]     # semitones from A: Am, F, C, G
    bars = int(np.ceil(duration / bar)) + 1
    k, h, c = kick(), None, None
    for b in range(bars):
        at = b * bar
        pos = at / duration
        root, third, fifth = chords[b % 4]
        full = 0.22 <= pos < 0.86
        build = 0.10 <= pos < 0.92
        # pad: three detuned voices an octave up, slow attack
        pn = int((bar + 0.6) * SR)
        pad = sum(saw(note(s + 12), pn, cutoff=1500 + 900 * full, detune=d) for s in (root, third, fifth) for d in (-0.003, 0.004))
        pad = pad * env(pn, 0.7, 0.9) * 0.05
        place(track, np.stack([pad, np.roll(pad, 240)], axis=1), at)
        if build:
            # arpeggio: sixteenth notes up the chord, with an echo
            seq = [root, third, fifth, root + 12, fifth, third, root + 12, fifth]
            for i in range(16):
                an = int(0.22 * SR)
                tone = saw(note(seq[i % 8] + 24), an, cutoff=5200) * np.exp(-np.arange(an) / SR * 16) * 0.10
                when = at + i * beat / 4
                pan = 0.5 + 0.35 * np.sin(i * 1.3)
                st = np.stack([tone * (1 - pan), tone * pan], axis=1) * 2
                place(track, st, when)
                place(track, st[:, ::-1], when + beat * 0.75, 0.35)
            for i in range(8):
                place(track, hat(rng), at + i * beat / 2, 0.07 if i % 2 == 0 else 0.11)
        if full:
            for i in range(8):                                    # eighth-note bass on the root
                bn = int(beat / 2 * SR)
                tb = np.arange(bn) / SR
                f = note(root - 12)
                tone = (np.sin(2 * np.pi * f * tb) + 0.35 * np.sin(4 * np.pi * f * tb)) * env(bn, 0.004, 0.05) * np.exp(-tb * 5)
                place(track, tone.astype(np.float32), at + i * beat / 2, 0.30)
            for i in range(4):
                place(track, k, at + i * beat, 0.55)
            for i in (1, 3):
                place(track, clap(rng), at + i * beat, 0.16)
    track = track[:int(duration * SR)]
    track[:int(1.2 * SR)] *= np.linspace(0, 1, int(1.2 * SR))[:, None]
    tail = int(min(3.0, duration / 4) * SR)
    track[-tail:] *= np.linspace(1, 0, tail)[:, None] ** 1.5
    return track / (np.max(np.abs(track)) + 1e-9) * 0.8


def make_test_tone(duration):
    """Plain test bed for technical checks: a quiet 220 Hz tone with a 1 kHz tick each second."""
    n = int(duration * SR)
    t = np.arange(n) / SR
    out = np.sin(2 * np.pi * 220 * t) * 0.15
    for s in range(int(duration)):
        tick = np.sin(2 * np.pi * 1000 * np.arange(int(0.03 * SR)) / SR) * 0.4
        out[s * SR:s * SR + len(tick)] += tick
    return np.stack([out, out], axis=1).astype(np.float32)


# ---------- narration ----------
SAPI_SCRIPT = ('Add-Type -AssemblyName System.Speech; '
               '$s = New-Object System.Speech.Synthesis.SpeechSynthesizer; '
               '$t = [IO.File]::ReadAllText($env:STUDIO_NARR_TXT, [Text.Encoding]::UTF8); '
               '$s.SetOutputToWaveFile($env:STUDIO_NARR_OUT); $s.Speak($t); $s.Dispose()')


def speak(text, path, engine):
    """Synthesise one line to `path`. Returns the engine actually used."""
    if engine == 'elevenlabs':
        import sys
        sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'integrations'))
        import elevenlabs_tts
        elevenlabs_tts.synthesise(text, path)                    # raises with instructions if no key is set
        return 'elevenlabs'
    if engine == 'sapi':
        # The script is a constant: the text and the output path travel as data (a file and
        # environment variables), never as PowerShell source, so narration text cannot run as code.
        txt = os.path.splitext(path)[0] + '.txt'
        with open(txt, 'w', encoding='utf-8') as f:
            f.write(text)
        r = subprocess.run(['powershell', '-NoProfile', '-NonInteractive', '-Command', SAPI_SCRIPT], capture_output=True, text=True,
                           env={**os.environ, 'STUDIO_NARR_TXT': os.path.abspath(txt), 'STUDIO_NARR_OUT': os.path.abspath(path)})
        os.remove(txt)
        if r.returncode == 0 and os.path.exists(path) and os.path.getsize(path) > 1000:
            return 'sapi'
        engine = 'flite'
    if engine == 'flite':
        txt = os.path.splitext(path)[0] + '.txt'
        with open(txt, 'w', encoding='utf-8') as f:
            f.write(text)
        rel = os.path.relpath(txt).replace('\\', '/')
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'lavfi', '-i', f"flite=textfile='{rel}':voice=slt", path], check=True)
        os.remove(txt)
        return 'flite'
    raise ValueError(f'unknown narration engine {engine}')


# ---------- the build ----------
def measure(path):
    """Integrated loudness (LUFS) and true peak (dBTP) of a file, by EBU R128."""
    r = subprocess.run(['ffmpeg', '-hide_banner', '-nostats', '-i', path, '-af', 'ebur128=peak=true', '-f', 'null', '-'],
                       capture_output=True, text=True, encoding='utf-8', errors='replace')
    tail = r.stderr[r.stderr.rfind('Summary:'):]
    i = re.search(r'I:\s+(-?[\d.]+) LUFS', tail)
    tp = re.search(r'Peak:\s+(-?[\d.]+) dBFS', tail)
    return (float(i.group(1)) if i else None, float(tp.group(1)) if tp else None)


def loudnorm(src, dst, target=QA['loudness_target_lufs'], peak=-3.0):
    """Bring the mix to the target loudness: gain, then a limiter that holds the peak ceiling.
    Repeats with a corrected gain because the limiter takes a little loudness back."""
    measured, _ = measure(src)
    gain = target - measured
    for _ in range(4):
        af = f'volume={gain:.2f}dB,alimiter=limit={db(peak):.4f}:attack=5:release=60:level=disabled'
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', src, '-af', af, '-ar', str(SR), '-ac', '2', '-c:a', 'pcm_s16le', dst], check=True)
        got, tp = measure(dst)
        if abs(got - target) <= 0.3:
            break
        gain += target - got
    return {'input_lufs': measured, 'output_lufs': got, 'output_true_peak': tp, 'gain_db': round(gain, 2)}


def build(slug, quiet=False):
    project = timeline.load(slug)
    pdir = project['_dir']
    spec = project.get('audio', {})
    adir = os.path.join(pdir, 'audio')
    os.makedirs(adir, exist_ok=True)
    total = timeline.total_duration(project)
    n = int(total * SR)
    rng = np.random.default_rng(11)
    plan = {'duration': total, 'sample_rate': SR, 'stems': {}, 'narration': [], 'notes': []}

    # music
    music = np.zeros((n, 2), dtype=np.float32)
    mspec = spec.get('music') or {}
    if mspec.get('file'):
        clip = read_audio(os.path.join(pdir, mspec['file']))
        clip = clip[int(float(mspec.get('start', 0)) * SR):][:n].copy()
        fi, fo = int(float(mspec.get('fade_in', 0.05)) * SR), int(float(mspec.get('fade_out', 2.0)) * SR)
        if fi:
            clip[:fi] *= np.linspace(0, 1, fi)[:, None]
        if fo and len(clip) >= n:
            clip[-fo:] *= np.linspace(1, 0, fo)[:, None] ** 1.5
        place(music, clip, 0)
        plan['music'] = {'file': mspec['file'], 'start': float(mspec.get('start', 0))}
        plan['notes'].append(f"music from file {mspec['file']}, starting {float(mspec.get('start', 0)):.3f}s into it")
    elif mspec.get('generator') == 'test-tone':
        music = make_test_tone(total)[:n]
        plan['notes'].append('music: generated test tone (labelled test audio)')
    elif mspec.get('generator', 'synth') == 'synth':
        music = make_music(total, bpm=mspec.get('bpm', 104), seed=mspec.get('seed', 6))[:n]
        plan['notes'].append(f"music: original synth score generated by video/engine/audio.py (bpm {mspec.get('bpm', 104)}, seed {mspec.get('seed', 6)})")
    music_gain = db(mspec.get('gain_db', -6.0))

    # narration
    narr = np.zeros((n, 2), dtype=np.float32)
    nspec = spec.get('narration') or {}
    engine = nspec.get('engine', 'none')
    duck = np.ones(n, dtype=np.float32)
    if engine != 'none':
        for i, line in enumerate(timeline.narration(project)):
            path = os.path.join(adir, f'narration-{i + 1:02d}.wav')
            used = speak(line['text'], path, engine)
            clip = read_audio(path)
            loud = np.where(np.abs(clip).max(axis=1) > 0.02)[0]
            if len(loud):                                         # trim the engine's leading and trailing silence
                clip = clip[max(0, loud[0] - 480):loud[-1] + 2400]
            clip = clip / (np.max(np.abs(clip)) + 1e-9) * 0.85
            place(narr, clip, line['start'])
            end = line['start'] + len(clip) / SR
            plan['narration'].append({'scene': line['scene'], 'start': line['start'], 'end': round(end, 3), 'text': line['text'], 'engine': used,
                                      'file': f'audio/narration-{i + 1:02d}.wav'})
            a, b = int(max(0, line['start'] - 0.3) * SR), int(min(total, end + 0.4) * SR)
            duck[a:b] = db(-float(nspec.get('duck_db', 12)))
        k = int(0.25 * SR)                                        # smooth the ducking so it never clicks
        csum = np.cumsum(np.pad(duck.astype(np.float64), (k // 2 + 1, k // 2), mode='edge'))
        duck = ((csum[k:] - csum[:-k]) / k)[:n].astype(np.float32)
        plan['notes'].append(f"narration engine: {engine}" + (' (TEST NARRATION, synthetic voice)' if engine in ('sapi', 'flite') else ''))

    # effects on transitions and titles
    sfx = np.zeros((n, 2), dtype=np.float32)
    if spec.get('sfx', True):
        for s in timeline.schedule(project):
            if s['transition_duration'] > 0:
                place(sfx, whoosh(rng, max(0.6, s['transition_duration'] + 0.3)), s['end'] - s['transition_duration'] - 0.15, 0.30 * db(spec.get('sfx_gain_db', 0)))
        for s, sc in zip(project['scenes'], timeline.schedule(project)):
            if s['type'] == 'title' and s.get('impact', True):
                place(sfx, impact(rng), sc['start'] + 0.3, 0.55 * db(spec.get('sfx_gain_db', 0)))

    music_out = music * music_gain * duck[:, None]
    stems = {'music': music_out, 'narration': narr, 'sfx': sfx}
    for name, data in stems.items():
        if np.max(np.abs(data)) > 0:
            write_wav(os.path.join(adir, name + '.wav'), data)
            plan['stems'][name] = f'audio/{name}.wav'
    mix = music_out + narr + sfx
    peak = float(np.max(np.abs(mix)))
    if peak == 0:
        plan['notes'].append('no audio sources: the mix is silent')
    else:
        mix = mix / peak * db(-3)
    raw = os.path.join(adir, 'mix-raw.wav')
    write_wav(raw, mix)
    out = os.path.join(pdir, spec.get('mix', 'audio/mix.wav'))
    if peak > 0:
        plan['loudnorm_input'] = loudnorm(raw, out)
    else:
        os.replace(raw, out)
    if os.path.exists(raw):
        os.remove(raw)
    with open(os.path.join(adir, 'mix-plan.json'), 'w', encoding='utf-8') as f:
        json.dump(plan, f, indent=1)
    if not quiet:
        print(f'{out}: {total:.2f}s; stems: {", ".join(plan["stems"]) or "none"}')
        for note_ in plan['notes']:
            print('  ' + note_)
    return out
