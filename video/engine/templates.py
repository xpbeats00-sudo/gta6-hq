"""Starter projects for each kind of video. Every template renders as it stands (generated scenes only),
so a new production can be previewed before any footage exists."""

NOTICE = 'Unofficial fan project. Not affiliated with or endorsed by Rockstar Games or Take-Two Interactive.'
BADGE = 'Unofficial fan project'


def _base(title, kind, fmt):
    return {'meta': {'title': title, 'kind': kind, 'format': fmt, 'fps': 30, 'fade_in': 0.4, 'fade_out': 0.6,
                     'must_say': ['unofficial'], 'must_not_say': ['official app', 'release date']},
            'captions': {'burn_in': True}, 'scenes': []}


def _title(i, title, kicker, subtitle, d=4.0, tr='slant'):
    return {'id': f's{i:02d}', 'type': 'title', 'duration': d, 'kicker': kicker, 'title': title, 'subtitle': subtitle,
            'badge': BADGE, 'no_claims': True, 'transition': {'type': tr, 'duration': 0.6}}


def _card(i, heading, items, d=6.0, tr='crossfade'):
    return {'id': f's{i:02d}', 'type': 'card', 'duration': d, 'heading': heading, 'items': items, 'badge': BADGE,
            'claims': [], 'transition': {'type': tr, 'duration': 0.5}}


def _credits(i, d=5.0):
    return {'id': f's{i:02d}', 'type': 'credits', 'duration': d, 'heading': 'Credits',
            'lines': [['Made with', 'the GTA 6 HQ video studio'], ['Music', 'original, generated by the studio']], 'notice': NOTICE, 'no_claims': True}


def make(kind, title, fmt):
    p = _base(title, kind, fmt)
    s = p['scenes']
    if kind in ('cinematic-trailer', 'game-trailer', 'promotional'):
        s += [_title(1, title, 'Replace this kicker', 'Replace this subtitle', 3.5, 'flash'),
              _card(2, 'Beat one', ['Replace with a filmed scene (type "footage")', 'Keep each beat to one idea'], 5.0, 'slant'),
              _card(3, 'Beat two', ['Second idea', 'Third idea'], 5.0, 'push'),
              _title(4, 'Call to action', 'Where to get it', 'Replace this line', 4.0, 'crossfade'), _credits(5)]
        p['audio'] = {'music': {'generator': 'synth', 'bpm': 112 if kind != 'cinematic-trailer' else 92}, 'narration': {'engine': 'none'}, 'sfx': True}
    elif kind == 'documentary':
        s += [_title(1, title, 'A documentary', 'Replace this subtitle', 5.0, 'crossfade'),
              _card(2, 'Chapter one', ['Replace with stills (type "still") or footage', 'Every statement needs a claim id'], 8.0),
              _card(3, 'Chapter two', ['Narration belongs in the scene\'s "narration" field'], 8.0), _credits(4, 6.0)]
        p['audio'] = {'music': {'generator': 'synth', 'bpm': 84, 'gain_db': -10}, 'narration': {'engine': 'none'}, 'sfx': False}
    elif kind in ('tutorial', 'explainer'):
        s += [_title(1, title, 'How to' if kind == 'tutorial' else 'Explained', 'Replace this subtitle', 3.5, 'crossfade'),
              _card(2, 'Step one', ['Do this first', 'Then this'], 7.0, 'push'), _card(3, 'Step two', ['Then this', 'And this'], 7.0, 'push'),
              _card(4, 'Recap', ['Step one', 'Step two'], 5.0), _credits(5, 4.0)]
        p['audio'] = {'music': {'generator': 'synth', 'bpm': 96, 'gain_db': -12}, 'narration': {'engine': 'none'}, 'sfx': True}
    elif kind == 'animated-infographic':
        s += [_title(1, title, 'By the numbers', 'Replace this subtitle', 3.5, 'slant'),
              {'id': 's02', 'type': 'stats', 'duration': 7.0, 'heading': 'Replace this heading', 'badge': BADGE, 'claims': [],
               'stats': [{'value': 10, 'label': 'Replace: each number needs a claim'}, {'value': 20, 'label': 'Second number'}, {'value': 30, 'label': 'Third number'}],
               'source': 'Source: replace with where the numbers come from', 'transition': {'type': 'crossfade', 'duration': 0.5}},
              _credits(3, 4.5)]
        p['audio'] = {'music': {'generator': 'synth', 'bpm': 104}, 'narration': {'engine': 'none'}, 'sfx': True}
    else:
        raise ValueError(kind)
    return p


